# penugasan pertama
a = 8
print('a = 8 -> ', a)

a += 3
print('a += 3 -> ', a)

a -= 1
print('a -= 1 -> ', a)

a *= 4
print('a *= 4 -> ', a)

a /= 8
print('a /= 8 -> ', a)


# karena a jadi float, kita ubah lagi menjadi integer
a = int(a)

a %= 7
print('a %= 7 -> ', a)

a //= 4
print('a //= 4 -> ', a)

a **= 2
print('a **= 2 -> ', a)